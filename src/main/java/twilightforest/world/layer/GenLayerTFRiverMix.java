package twilightforest.world.layer;

import net.minecraft.world.gen.layer.GenLayer;
import net.minecraft.world.gen.layer.IntCache;

import twilightforest.TwilightForestMod;
import twilightforest.biomes.TFBiomeBase;

public class GenLayerTFRiverMix extends GenLayer {

    private final GenLayer biomeLayer;
    private final GenLayer riverLayer;

    public GenLayerTFRiverMix(long seed, GenLayer biomeLayer, GenLayer riverLayer) {
        super(seed);
        this.biomeLayer = biomeLayer;
        this.riverLayer = riverLayer;
    }

    /**
     * Initialize layer's local worldGenSeed based on its own baseSeed and the world's global seed (passed in as an
     * argument).
     */
    @Override
    public void initWorldGenSeed(long worldSeed) {
        // preserve both initialisations, the river layer also references the biome layer
        biomeLayer.initWorldGenSeed(worldSeed);
        riverLayer.initWorldGenSeed(worldSeed);
        super.initWorldGenSeed(worldSeed);
    }

    /**
     * Returns a list of integer values generated by this layer. These may be interpreted as temperatures, rainfall
     * amounts, or biomeList[] indices based on the particular GenLayer subclass.
     */
    @Override
    public int[] getInts(int x, int z, int width, int depth) {
        int[] biomeInputs = biomeLayer.getInts(x, z, width, depth);
        int[] riverInputs = riverLayer.getInts(x, z, width, depth);
        int size = width * depth;
        int[] output = IntCache.getIntCache(size);

        int streamId = TFBiomeBase.stream.biomeID;
        // preserve the original biome ID mask to avoid changing existing world gen
        int maskedStreamId = streamId & (TwilightForestMod.maxBiomeIDs - 1);

        for (int i = 0; i < size; i++) {
            output[i] = riverInputs[i] == streamId ? maskedStreamId : biomeInputs[i];
        }

        return output;
    }
}
